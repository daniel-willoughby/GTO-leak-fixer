// Generate the PotKing wordmark as STATIC outlined SVG paths from Bodoni Z37.
//
// Licensing note: Bodoni Z37 ships under Typodermic's *Desktop* EULA, which
// permits creating static graphic images (outlines) but NOT embedding the font
// software in a website / public repo. This script runs on a workstation, reads
// the licensed .otf, and emits vector OUTLINES only — the font file is never
// committed. Output paths contain no font software.
//
// Usage: node scripts/gen-wordmark.mjs "/path/to/Bodoni Z37 M Compressed Bold.otf"
import opentype from 'opentype.js'
import { readFileSync, writeFileSync } from 'node:fs'

const fontPath = process.argv[2]
if (!fontPath) {
  console.error('Pass the path to the licensed Bodoni Z37 Compressed Bold .otf')
  process.exit(1)
}

const buf = readFileSync(fontPath)
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))
const SIZE = 100 // arbitrary em size; the SVG is scaled by viewBox at render time

// Lay out "Pot·King" with the middle dot as its own group so it can be tinted.
const segments = ['Pot', '·', 'King']
let x = 0
const groups = []
for (const seg of segments) {
  const path = font.getPath(seg, x, 0, SIZE, { kerning: true })
  groups.push(path.toPathData(3))
  x += font.getAdvanceWidth(seg, SIZE, { kerning: true })
}

// Bounding box across everything, so the viewBox hugs the glyphs.
let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity
x = 0
for (const seg of segments) {
  const p = font.getPath(seg, x, 0, SIZE, { kerning: true })
  const bb = p.getBoundingBox()
  minX = Math.min(minX, bb.x1); minY = Math.min(minY, bb.y1)
  maxX = Math.max(maxX, bb.x2); maxY = Math.max(maxY, bb.y2)
  x += font.getAdvanceWidth(seg, SIZE, { kerning: true })
}
const pad = SIZE * 0.04
const vbX = minX - pad, vbY = minY - pad
const vbW = maxX - minX + pad * 2, vbH = maxY - minY + pad * 2

const round = (n) => Number(n.toFixed(2))
const viewBox = `${round(vbX)} ${round(vbY)} ${round(vbW)} ${round(vbH)}`

const component = `// AUTO-GENERATED by scripts/gen-wordmark.mjs — do not edit by hand.
// Static outlined "Pot·King" wordmark in Bodoni Z37 Compressed Bold. These are
// vector outlines (a static graphic image), not the font software, so they're
// compliant with the Typodermic Desktop EULA. The font file is NOT in this repo.

/** The PotKing wordmark. Ink letters inherit currentColor; the dot is sage. */
export function Wordmark({ className = 'h-5' }: { className?: string }) {
  return (
    <svg
      viewBox="${viewBox}"
      className={className}
      role="img"
      aria-label="PotKing"
      style={{ width: 'auto' }}
      fill="currentColor"
    >
      <path d="${groups[0]}" />
      <path d="${groups[1]}" className="fill-sage" />
      <path d="${groups[2]}" />
    </svg>
  )
}
`

const out = new URL('../src/components/Wordmark.tsx', import.meta.url)
writeFileSync(out, component)
console.log(`Wrote ${out.pathname} (viewBox ${viewBox})`)
